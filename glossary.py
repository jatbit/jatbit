def _norm(s: str) -> str:
    s = re.sub(r"<[^>]+>", "", str(s))
    return s.strip()


def tip(label: str):
    """지표 이름 → 설명 (없으면 None)."""
    s = _norm(label)
    if s in G:
        return G[s]
    base = re.sub(r"\s*\(.*?\)\s*", " ", s).strip()  # 괄호 안 설명 제거
    base = re.sub(r"\s+", " ", base)
    if base in G:
        return G[base]
    for pat, key in PATTERNS:
        if re.search(pat, s):
            return G.get(key)
    return None


