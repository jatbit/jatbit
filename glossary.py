def icon(text) -> str:
    """동그라미 안 ? 아이콘 (마우스를 올리거나 탭하면 설명이 뜸)."""
    if not text:
        return ""
    return f'<span class="qt" tabindex="0">?<span class="qb">{html.escape(text)}</span></span>'


def label_html(label: str, extra=None) -> str:
    return html.escape(label) + icon(tip(label) or extra)


def col_help(columns) -> dict:
    """st.dataframe column_config: 열 이름에 설명이 있으면 머리글에 마우스를 올렸을 때 보이게 한다."""
    import streamlit as st

    out = {}
    for c in columns:
        t = tip(str(c))
        if t:
            out[c] = st.column_config.Column(help=t)
    return out


def table_html(rows: list, header: list, label_col: int = 0) -> str:
    """첫 열(지표 이름)에 ? 설명을 붙인 간단한 HTML 표."""
    th = "".join(f'<th class="{"qr" if i >= len(header) / 2 else ""}" style="text-align:{"left" if i == label_col else "right"};padding:4px 8px;border-bottom:1px solid rgba(128,128,128,.35);'
                 f'font-weight:600">{label_html(h) if i != label_col else html.escape(h)}</th>' for i, h in enumerate(header))
    body = ""
    for r in rows:
        tds = ""
        for i, v in enumerate(r):
            if i == label_col:
                tds += f'<td style="padding:4px 8px;white-space:nowrap">{label_html(str(v))}</td>'
            else:
                tds += f'<td style="padding:4px 8px;text-align:right">{html.escape(str(v))}</td>'
        body += f'<tr style="border-bottom:1px solid rgba(128,128,128,.15)">{tds}</tr>'
    out = (CSS + '<div><table style="border-collapse:collapse;font-size:0.82rem;width:100%">'  # 설명 팝업이 잘리지 않게 스크롤 상자 없이
           f"<thead><tr>{th}</tr></thead><tbody>{body}</tbody></table></div>")
    return out.replace("$", "&#36;")
